import { createTestRoot } from "@gpuix/solid/testing";
import { App } from "../src/app";
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
const t = createTestRoot({ width: 1100, height: 720 });
const r = t.renderer;
t.render(() => <App />);
await sleep(300);
r.flush();
r.getElementBounds(1);
await sleep(300);
r.flush();
const c = (id: string) => {
	const e = r.findByTestId(id)!;
	const b = r.getElementBounds(e.id)!;
	return { x: b.x + b.width / 2, y: b.y + b.height / 2 };
};
const settle = async (ms = 400) => {
	await sleep(ms);
	r.flush();
};
let p = c("framework-input");
r.nativeSimulateClick(p.x, p.y);
await settle(500);
// scroll popup
r.nativeSimulateScrollWheel(560, 300, 0, -120);
await settle(300);
r.nativeSimulateMouseMove(560, 250);
await settle(300);
r.captureScreenshot("/tmp/c1-scrolled.png");
r.simulateKeystrokes("backspace backspace backspace backspace backspace");
await settle(300);
r.simulateKeystrokes("s o l");
await settle(500);
r.captureScreenshot("/tmp/c2-filtered.png");
r.simulateKeystrokes("z z");
await settle(500);
r.captureScreenshot("/tmp/c3-empty.png");
r.simulateKeystrokes("backspace backspace backspace");
await settle(400);
r.simulateKeystrokes("down down down");
await settle(400);
r.captureScreenshot("/tmp/c4-keys.png");
r.simulateKeystrokes("enter");
await settle(500);
r.captureScreenshot("/tmp/c5-picked.png");
console.log("done");
process.exit(0);
